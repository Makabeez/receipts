#!/usr/bin/env python3
"""Regenerate lib/sui-ledger-desc.ts: the Sui gRPC LedgerService schema (FileDescriptorSet, base64),
read by server reflection from a public Sui fullnode. Run from the app folder:
    pip install grpcio grpcio-reflection protobuf && python3 scripts/gen-sui-desc.py
"""
import base64
import grpc
from google.protobuf import descriptor_pb2
from google.protobuf.descriptor_pool import DescriptorPool
from grpc_reflection.v1alpha.proto_reflection_descriptor_database import ProtoReflectionDescriptorDatabase

ch = grpc.secure_channel("fullnode.mainnet.sui.io:443", grpc.ssl_channel_credentials())
pool = DescriptorPool(ProtoReflectionDescriptorDatabase(ch))
svc = pool.FindServiceByName("sui.rpc.v2.LedgerService")
fds, seen = descriptor_pb2.FileDescriptorSet(), set()

def add(fd):
    if fd.name in seen:
        return
    for dep in fd.dependencies:
        add(dep)
    seen.add(fd.name)
    p = descriptor_pb2.FileDescriptorProto()
    fd.CopyToProto(p)
    fds.file.append(p)

add(svc.file)
b64 = base64.b64encode(fds.SerializeToString()).decode()
with open("lib/sui-ledger-desc.ts", "w") as f:
    f.write("// Generated by scripts/gen-sui-desc.py: Sui gRPC LedgerService schema (FileDescriptorSet, base64).\n")
    f.write(f'export const SUI_LEDGER_DESC_B64 =\n  "{b64}";\n')
print(f"wrote lib/sui-ledger-desc.ts ({len(fds.file)} files, {len(b64)} chars)")
